-- 同期まわりの進捗を記録する小さな key-value。
--
-- 過去の一括取り込みが「もう終わったか」を持つために入れる。
-- それまでは「保有する最古のイベントが取り込み下限より古いか」で判定していたが、
-- CTFTime 自体の最古が 2010-04-26 で下限に届かないため条件が永久に成立せず、
-- 端まで到達したあとも 15 分ごとに同じ範囲を取得し続けていた。
--
-- 完了時に指定日数を値として残すので、範囲を広げたときだけ再実行される。

CREATE TABLE sync_state (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
